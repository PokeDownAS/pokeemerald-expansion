def make_mon(species, level, item, moves, iv=24):
    return "\n".join([
        f"{species} @ {item}",
        f"Level: {level}",
        f"IVs: {iv} HP / {iv} Atk / {iv} Def / {iv} SpA / {iv} SpD / {iv} Spe",
        *[f"- {move}" for move in moves],
    ])


def patch_meta(meta, doubles=False):
    lines = meta.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("AI:"):
            lines[i] = "AI: Check Bad Move / Try To Faint / Check Viability"
            break
    else:
        lines.append("AI: Check Bad Move / Try To Faint / Check Viability")
    if doubles:
        for i, line in enumerate(lines):
            if line.startswith("Double Battle:"):
                lines[i] = "Double Battle: Yes"
                break
    return "\n".join(lines)


def main():
    text = TRAINERS.read_text()
    labels = set(re.findall(r"^=== (TRAINER_[A-Z0-9_]+) ===$", text, re.M))
    missing = sorted((set(ADMIN_TEAMS) | set(SUPERBOSSES)) - labels)
    if missing:
        raise RuntimeError("Missing trainer labels: " + ", ".join(missing))

    changed_admin = changed_super = 0
    for label, team in {**ADMIN_TEAMS, **SUPERBOSSES}.items():
        pat = re.compile(rf"(=== {re.escape(label)} ===\n)(.*?)(?=\n=== TRAINER_|\Z)", re.S)
        m = pat.search(text)
        if not m:
            raise RuntimeError(f"Could not find {label}")
        body = m.group(2)
        if "\n\n" not in body:
            raise RuntimeError(f"Malformed trainer block: {label}")
        meta, _old_party = body.split("\n\n", 1)
        meta = patch_meta(meta, doubles=(label == "TRAINER_TATE_AND_LIZA_5"))
        iv = 30 if label in SUPERBOSSES else 20
        party = "\n\n".join(make_mon(s, l, i, moves, iv) for s, l, i, moves in team)
        repl = m.group(1) + meta.rstrip() + "\n\n" + party + "\n"
        text = text[:m.start()] + repl + text[m.end():]
        if label in SUPERBOSSES:
            changed_super += 1
        else:
            changed_admin += 1

    TRAINERS.write_text(text)
    print(f"Admin/postgame pass: hand-tuned {changed_admin} Aqua/Magma Admin fights and {changed_super} final Gym rematch superbosses.")


if __name__ == "__main__":
    main()
